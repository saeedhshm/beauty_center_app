type Variables = Record<string, string | number>;

function interpolate(message: string, variables?: Variables): string {
  if (!variables) return message;
  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(variables[key] ?? ''));
}

export function readStoredLocale(): Locale {
  try {
    return window.localStorage.getItem(LOCALE_STORAGE_KEY) === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}

export function translate(locale: Locale, arabic: string, variables?: Variables): string {
  return interpolate(locale === 'en' ? (english[arabic] ?? arabic) : arabic, variables);
}

export function hasEnglishTranslation(arabic: string): boolean {
  return Object.hasOwn(english, arabic);
}

interface I18nValue {
  locale: Locale;
  direction: Direction;
  setLocale: (locale: Locale) => void;
  t: (arabic: string, variables?: Variables) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function getActiveLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored === 'ar' || stored === 'en') return stored;
  } catch {
    // Fall back to the document direction when browser storage is unavailable.
  }
  return document.documentElement.lang === 'en' ? 'en' : 'ar';
}

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => initialLocale ?? readStoredLocale());
  const direction: Direction = locale === 'ar' ? 'rtl' : 'ltr';

  const setLocale = (next: Locale) => {
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch {
      // A blocked storage API must not prevent changing the current interface language.
    }
    document.documentElement.lang = next;
    document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
    setLocaleState(next);
  };

  useLayoutEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
    document.title = translate(locale, 'لوحة إدارة لمسة');
  }, [direction, locale]);

  return (
    <I18nContext.Provider value={{ locale, direction, setLocale, t: (message, variables) => translate(locale, message, variables) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
